let current = 'en';
let variant = ''; // '' or 'note': see the header

/** `tr` when the browser language starts with `tr`, otherwise `en`. */
export function detectLang(navigatorLanguage) {
  return typeof navigatorLanguage === 'string' && navigatorLanguage.toLowerCase().startsWith('tr')
    ? 'tr'
    : 'en';
}

/** Fills `{name}` placeholders; a placeholder without a value stays as written. */
export function format(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole);
}

/** The entry of `key` in `lang`: its variant (`<key>.note`) first while the page shows a source of notes. */
function lookup(lang, key) {
  const dict = DICT[lang];
  return (variant === '' ? undefined : dict[`${key}.${variant}`]) ?? dict[key];
}

/** Looks up a string in the current language (English, then the key itself, as fallbacks). */
export function t(key, params) {
  return format(lookup(current, key) ?? lookup('en', key) ?? key, params);
}

/**
 * Looks up a string that depends on a count: `<key>.one` or `<key>.other`, whichever the current
 * language's plural rules pick for `count`. `{n}` in the text is the count.
 */
export function tn(key, count, params) {
  const category = new Intl.PluralRules(current).select(count);
  const text = lookup(current, `${key}.${category}`) ?? lookup(current, `${key}.other`)
    ?? lookup('en', `${key}.${category}`) ?? lookup('en', `${key}.other`) ?? key;
  return format(text, { ...params, n: count });
}

/** `'note'` while the page shows a source of notes, `''` otherwise: the strings that read differently there are picked up by t() and tn(). */
export function setVariant(name) {
  variant = name === 'note' ? 'note' : '';
}

export function getVariant() {
  return variant;
}

export function getLang() {
  return current;
}

/** Switches the language and remembers it (storage may be unavailable; that is fine). */
export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Storage can be blocked or missing; the choice then lasts for this page only.
  }
}

/** Picks the start language: the stored choice, else the browser language. */
export function initLang() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch {
    // See setLang.
  }
  const browser = typeof navigator !== 'undefined' ? navigator.language : undefined;
  current = LANGS.includes(stored) ? stored : detectLang(browser);
  return current;
}
