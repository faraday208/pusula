// pusula - UI strings (Turkish and English). All visible text comes from here.
//
// `{name}` marks a placeholder that t() fills in. Keys that end in an enum value
// (`layer.*`, `load.*`, `loadShort.*`, `status.*`, `tip.*`, `kind.*`) are looked up with the values
// the API sends. `load.*` is the full name, `loadShort.*` the short one for tight table cells.
// A key with a count has two entries, `<key>.one` and `<key>.other`, and is read with tn().
// `info.lines` is read with tn() too, but its `{lines}` is not filled in here: the page puts the line
// numbers (links, not text) in that place, so a language can put them before or after the word.
//
// A key that reads differently in a source of notes (an Obsidian vault, a Markdown folder) has a second entry,
// `<key>.note` (a plural one is `<key>.one.note`, `<key>.other.note`). While the page shows such a source it has
// called `setVariant('note')`, and t() and tn() prefer that entry; everything else reads the same in both.

